import bcrypt from "bcryptjs";
import Employee from "../models/Employee.js";
import Counter from "../models/Counter.js";
import { sendEmployeeWelcomeMail } from "../utils/email.js";
import { createNotification } from "../services/notification.service.js";
import cloudinary from "../config/cloudinary.js";

// The photo is uploaded before this runs; a refused request must not leave it behind
const discardUpload = async (file) => {
  if (!file?.filename) return;
  await cloudinary.uploader
    .destroy(file.filename)
    .catch((error) => console.error("PROFILE PHOTO CLEANUP FAILED:", error));
};

// ADMIN CREATE EMPLOYEE
export const createEmployee = async (req, res) => {
  try {
    const { name, email, password } = req.body;

    if (!name || !email || !password) {
      await discardUpload(req.file);
      return res.status(400).json({
        success: false,
        message: "All fields are required",
      });
    }

    // The creation form has always told admins the password needs at least 8
    // characters with upper case, lower case, a number and a symbol, but
    // nothing enforced it on either side — "1" was accepted.
    const strongPassword =
      /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[^A-Za-z0-9]).{8,}$/;

    if (!strongPassword.test(password)) {
      await discardUpload(req.file);
      return res.status(400).json({
        success: false,
        message:
          "Password must be at least 8 characters and include an uppercase letter, a lowercase letter, a number and a symbol",
      });
    }

    // 🔥 FIX: normalize before the duplicate check. The schema's unique
    // index is case-sensitive with no lowercase/trim, so "Test@x.com" and
    // "test@x.com " were treated as different values — letting the same
    // real address create two separate employee accounts.
    const trimmedEmail = email.trim().toLowerCase();

    const exists = await Employee.findOne({ email: trimmedEmail });
    if (exists) {
      await discardUpload(req.file);
      return res.status(400).json({
        success: false,
        message: "Employee already exists",
      });
    }

    // 📷 PROFILE IMAGE (OPTIONAL)
    let profilePic = {
      url: "",
      publicId: "",
    };

    if (req.file) {
      profilePic = {
        url: req.file.path, // Cloudinary URL
        publicId: req.file.filename, // Cloudinary public_id
      };
    }

    const hashedPassword = await bcrypt.hash(password, 10);

    // 🔥 FIX: employeeId used to be generated by counting existing
    // documents and incrementing — a classic race condition. Two
    // concurrent "create employee" requests can both read the same count
    // and both attempt to create the identical employeeId; the second one
    // then fails outright with an unhandled duplicate-key error (this
    // catch block had no retry, and no specific handling for it), instead
    // of just trying the next number. Switched to the same atomic
    // Counter + retry pattern already used in applyAgent/createStore.
    const currentYear = new Date().getFullYear();

    let employee;
    let retries = 5;

    while (retries > 0) {
      try {
        const counter = await Counter.findByIdAndUpdate(
          `employee-${currentYear}`,
          { $inc: { seq: 1 } },
          { new: true, upsert: true },
        );

        const employeeId = `EMP${currentYear}-${String(counter.seq).padStart(3, "0")}`;

        employee = await Employee.create({
          employeeId,
          name,
          email: trimmedEmail,
          password: hashedPassword,
          role: "EMPLOYEE",
          profilePic,
        });

        break;
      } catch (error) {
        if (error.code === 11000 && error.keyPattern?.employeeId) {
          console.warn("Duplicate employeeId, retrying...");
          retries--;
          continue;
        }
        throw error;
      }
    }

    if (!employee) {
      await discardUpload(req.file);
      return res.status(500).json({
        success: false,
        message: "Failed to generate unique employee ID",
      });
    }

    // 📧 SEND EMAIL (never blocks creation; the panel is told if it failed)
    const emailSent = await sendEmployeeWelcomeMail({
      name,
      email: trimmedEmail,
      employeeId: employee.employeeId,
    });

    return res.status(201).json({
      success: true,
      emailSent,
      message: emailSent
        ? "Employee created successfully"
        : `Employee created, but the welcome email could not be sent. Share the Employee ID ${employee.employeeId} with them directly.`,
      employeeId: employee.employeeId,
      profilePic: employee.profilePic,
    });
  } catch (error) {
    console.error("CREATE EMPLOYEE ERROR:", error);
    await discardUpload(req.file);

    // 🔥 FIX: gracefully handle a duplicate email slipping through a race
    // between the pre-check above and the actual insert, instead of a
    // generic 500 with no explanation.
    if (error.code === 11000) {
      const field = Object.keys(error.keyValue || {})[0];
      return res.status(409).json({
        success: false,
        message:
          field === "email"
            ? "Employee already exists"
            : `${field} already exists`,
      });
    }

    return res.status(500).json({
      success: false,
      message: "Failed to create employee",
    });
  }
};

// ADMIN - GET ALL ACTIVE EMPLOYEES
export const getAllEmployees = async (req, res) => {
  try {
    const employees = await Employee.find({ status: "ACTIVE" }) // ✅ only active
      .select("employeeId name email role permissions status createdAt")
      .sort({ createdAt: -1 });

    return res.json({
      success: true,
      count: employees.length,
      employees,
    });
  } catch (error) {
    console.error("GET ALL EMPLOYEES ERROR:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to fetch employees",
    });
  }
};

// ADMIN - UPDATE EMPLOYEE PERMISSIONS
export const updateEmployeePermissions = async (req, res) => {
  try {
    const { employeeId } = req.params;
    const { permissions } = req.body;

    const employee = await Employee.findOne({ employeeId });

    if (!employee) {
      return res.status(404).json({
        success: false,
        message: "Employee not found",
      });
    }

    // 🧠 Detect changes
    const previousPermissions = { ...employee.permissions };

    let granted = [];
    let revoked = [];

    for (const key in permissions) {
      if (permissions[key] === true && !previousPermissions[key]) {
        granted.push(key);
      }

      if (permissions[key] === false && previousPermissions[key]) {
        revoked.push(key);
      }
    }

    // ✅ Update permissions
    employee.permissions = {
      ...employee.permissions,
      ...permissions,
    };

    await employee.save();

    // 🔥 Send notification based on change
    if (granted.length > 0 || revoked.length > 0) {
      let message = "";

      if (granted.length > 0 && revoked.length === 0) {
        message = "New permissions granted. Please re-login.";
      } else if (revoked.length > 0 && granted.length === 0) {
        message = "Some permissions were removed. Access may be restricted.";
      } else {
        message = "Your permissions have been updated. Please re-login.";
      }

      await createNotification({
        title: "Permission Update",
        message,
        recipientId: employee._id, // ✅ always use _id
        recipientModel: "Employee",
        meta: {
          granted,
          revoked,
        },
      });
    }

    return res.json({
      success: true,
      message: "Permissions updated successfully",
      permissions: employee.permissions,
    });
  } catch (error) {
    console.error("UPDATE PERMISSION ERROR:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to update permissions",
    });
  }
};

// EMPLOYEE - GET OWN PROFILE
export const getEmployeeProfile = async (req, res) => {
  try {
    const employeeId = req.user.id; // coming from auth middleware

    const employee = await Employee.findById(employeeId).select("-password");

    if (!employee) {
      return res.status(404).json({
        success: false,
        message: "Employee not found",
      });
    }

    return res.status(200).json({
      success: true,
      employee,
    });
  } catch (error) {
    console.error("GET EMPLOYEE PROFILE ERROR:", error);

    return res.status(500).json({
      success: false,
      message: "Failed to fetch employee profile",
    });
  }
};

// ADMIN - SOFT DELETE EMPLOYEE
export const deleteEmployee = async (req, res) => {
  try {
    const { employeeId } = req.params;

    const employee = await Employee.findOne({ employeeId });

    if (!employee) {
      return res.status(404).json({
        success: false,
        message: "Employee not found",
      });
    }

    // ❗ Prevent admin deleting themselves
    if (employee._id.toString() === req.user.id) {
      return res.status(400).json({
        success: false,
        message: "You cannot delete your own account",
      });
    }

    // ❗ Already inactive check
    if (employee.status === "INACTIVE") {
      return res.status(400).json({
        success: false,
        message: "Employee already deleted",
      });
    }

    // ✅ SOFT DELETE
    employee.status = "INACTIVE";
    employee.isOnline = false;

    await employee.save();

    return res.status(200).json({
      success: true,
      message: "Employee deleted (soft) successfully",
    });
  } catch (error) {
    console.error("DELETE EMPLOYEE ERROR:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to delete employee",
    });
  }
};
